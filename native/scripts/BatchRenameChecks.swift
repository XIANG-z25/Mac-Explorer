import Foundation

@main enum BatchRenameChecks {
  static func main() throws {
    let fm = FileManager.default
    let root = fm.temporaryDirectory.appendingPathComponent("batch-rename-\(UUID().uuidString)")
    try fm.createDirectory(at: root, withIntermediateDirectories: true)
    defer { try? fm.removeItem(at: root) }
    var count = 0
    func check(_ condition: Bool, _ label: String) throws {
      count += 1
      if !condition { throw NSError(domain: "BatchRenameChecks", code: count, userInfo: [NSLocalizedDescriptionKey: label]) }
    }
    let first = root.appendingPathComponent("alpha.txt"), second = root.appendingPathComponent("beta.md")
    try Data("alpha".utf8).write(to: first); try Data("beta".utf8).write(to: second)
    let collision = root.appendingPathComponent("Report (2).md")
    try Data("original".utf8).write(to: collision)
    let rejected = FileActions.batchRename([first, second], baseName: "Report")
    try check(!rejected.errors.isEmpty && rejected.changes.isEmpty, "preflight rejects an existing target")
    try check(fm.fileExists(atPath: first.path) && fm.fileExists(atPath: second.path), "preflight preserves both sources")
    try check(try String(contentsOf: collision, encoding: .utf8) == "original", "collision content is untouched")
    try fm.removeItem(at: collision)
    let result = FileActions.batchRename([first, second], baseName: "Report")
    try check(result.errors.isEmpty && result.changes.count == 2, "two files renamed")
    try check(result.succeeded.map(\.lastPathComponent) == ["Report (1).txt", "Report (2).md"], "numbering preserves each extension")
    try check(try String(contentsOf: result.succeeded[0], encoding: .utf8) == "alpha", "first content preserved")
    try check(try String(contentsOf: result.succeeded[1], encoding: .utf8) == "beta", "second content preserved")
    let undone = FileActions.undo(result.changes)
    try check(undone.errors.isEmpty && fm.fileExists(atPath: first.path) && fm.fileExists(atPath: second.path), "one undo restores the batch")
    let invalid = FileActions.batchRename([first, second], baseName: "bad/name")
    try check(!invalid.errors.isEmpty && invalid.changes.isEmpty, "invalid names leave every source untouched")
    let insufficient = FileActions.batchRename([first], baseName: "Report")
    try check(!insufficient.errors.isEmpty && insufficient.changes.isEmpty, "one selection cannot run a batch")
    let folderOne = root.appendingPathComponent("Folder (old)", isDirectory: true)
    let folderTwo = root.appendingPathComponent("Folder [draft]", isDirectory: true)
    let photo = root.appendingPathComponent("alpha (draft).TXT")
    let image = root.appendingPathComponent("BETA [old].PNG")
    try fm.createDirectory(at: folderOne, withIntermediateDirectories: false)
    try fm.createDirectory(at: folderTwo, withIntermediateDirectories: false)
    try Data().write(to: photo); try Data().write(to: image)
    let options = BatchRenameOptions(prefix: "New-", suffix: "-Done", find: "alpha", replacement: "Photo", casing: .lowercase, removeBracketedContent: true, sequence: BatchRenameSequence(start: 9, padding: 3, separator: "_"), extensionOverride: "jpeg")
    let preview = FileActions.batchRenamePreview([folderOne, folderTwo, photo, image], options: options)
    try check(preview == ["New-folder-Done_009", "New-folder-Done_010", "New-photo-Done_011.jpeg", "New-beta-Done_012.jpeg"], "preview applies folder-safe rules, bracket removal, case, numbering and extension")
    let advanced = FileActions.batchRename([folderOne, folderTwo, photo, image], options: options)
    try check(advanced.errors.isEmpty && advanced.changes.count == 4, "advanced rules rename files and folders together")
    try check(advanced.succeeded.map(\.lastPathComponent) == preview, "advanced rules preserve the displayed preview")
    try check(fm.fileExists(atPath: advanced.succeeded[0].path) && advanced.succeeded[0].pathExtension.isEmpty, "folders never receive a file extension override")
    try check(fm.fileExists(atPath: advanced.succeeded[2].path) && advanced.succeeded[2].pathExtension == "jpeg", "files receive the requested extension override")
    let advancedUndo = FileActions.undo(advanced.changes)
    try check(advancedUndo.errors.isEmpty && fm.fileExists(atPath: folderOne.path) && fm.fileExists(atPath: photo.path), "advanced batch undo restores folders and files")
    let invalidExtension = FileActions.batchRename([folderOne, folderTwo], options: BatchRenameOptions(extensionOverride: "bad/name"))
    try check(!invalidExtension.errors.isEmpty && invalidExtension.changes.isEmpty, "invalid extension leaves folders untouched")
    let reference = "Episode-[www.example.com]-Author"
    let edited = "Episode-Author"
    let removed = FileActions.batchRenameRemovedText(original: reference, edited: edited)
    try check(removed == ["[www.example.com]-"], "editing a source name derives its deleted literal fragment")
    try check(FileActions.batchRenameRemovedText(original: reference, edited: "Episode-New-Author") == nil, "source-name editing rejects inserted text")
    let episode = root.appendingPathComponent(reference + ".mp4")
    let clip = root.appendingPathComponent("Clip-[www.example.com]-Author.mp4")
    try Data().write(to: episode); try Data().write(to: clip)
    let sourceEdit = FileActions.batchRename([episode, clip], options: BatchRenameOptions(removeTexts: removed ?? []))
    try check(sourceEdit.errors.isEmpty && sourceEdit.succeeded.map(\.lastPathComponent) == ["Episode-Author.mp4", "Clip-Author.mp4"], "removed source-name text applies to every selected similar name")
    let draftOne = root.appendingPathComponent("draft one.txt"), draftTwo = root.appendingPathComponent("draft two.txt")
    let finalOne = root.appendingPathComponent("final one.txt"), finalTwo = root.appendingPathComponent("final two.txt")
    try Data("draft-one".utf8).write(to: draftOne); try Data("draft-two".utf8).write(to: draftTwo)
    try Data("old-one".utf8).write(to: finalOne); try Data("old-two".utf8).write(to: finalTwo)
    let finalNames = BatchRenameOptions(find: "draft", replacement: "final")
    let conflicts = try FileActions.batchRenameConflicts([draftOne, draftTwo], options: finalNames)
    try check(conflicts.count == 2, "preflight reports only the colliding target names")
    try check(conflicts[0].source.lastPathComponent == "draft one.txt" && conflicts[0].destination.lastPathComponent == "final one.txt" && conflicts[0].sourceSize == Int64("draft-one".utf8.count) && conflicts[0].destinationSize == Int64("old-one".utf8.count), "conflict details identify both files and their sizes")
    let keepBoth = FileActions.batchRename([draftOne, draftTwo], options: finalNames, collisionPolicy: .keepBoth)
    try check(keepBoth.errors.isEmpty && keepBoth.succeeded.map(\.lastPathComponent) == ["final one (1).txt", "final two (1).txt"], "keep-both policy appends a Windows-style number")
    try check(try String(contentsOf: finalOne, encoding: .utf8) == "old-one", "keep-both policy preserves existing content")
    let incomingOne = root.appendingPathComponent("incoming one.txt"), incomingTwo = root.appendingPathComponent("incoming two.txt")
    try Data("new-one".utf8).write(to: incomingOne); try Data("new-two".utf8).write(to: incomingTwo)
    let replacement = BatchRenameOptions(find: "incoming", replacement: "final")
    let replaced = FileActions.batchRename([incomingOne, incomingTwo], options: replacement, collisionPolicy: .replace)
    try check(replaced.errors.isEmpty && replaced.succeeded.map(\.lastPathComponent) == ["final one.txt", "final two.txt"], "explicit replacement accepts existing targets")
    try check(try String(contentsOf: finalOne, encoding: .utf8) == "new-one", "explicit replacement writes the selected item over the target")
    print("BatchRenameChecks: \(count) assertions passed.")
  }
}
